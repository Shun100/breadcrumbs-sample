-- 標準機能だけで定義する場合
CREATE TABLE IF NOT EXISTS menus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    parent_id BIGINT REFERENCES menus(id)
);

-- 拡張機能ltree型を使用する場合
-- ltree型は階層構造のデータをドット区切りのパスで表現し、効率的に格納・探索することが可能
-- 例. home.product.list.detail
CREATE EXTENSION IF NOT EXISTS ltree; -- ltree型を使用するには拡張機能のインストールが必要
CREATE TABLE IF NOT EXISTS ltree_menus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    path LTREE NOT NULL UNIQUE
);

-- 階層検索用インデックス
CREATE INDEX IF NOT EXISTS idx_menus_path
    ON ltree_menus USING GIST (path);
